def build_full(cfg, en=False):
    parts = []
    parts.extend(cfg["hook"])
    parts.append("")
    for title, body in cfg["features"]:
        parts.append(f"■ {title}")
        parts.append(body)
        parts.append("")
    parts.append("■ Privacy" if en else "■ 개인정보")
    parts.extend(cfg["safety"])
    if cfg.get("disclaimer"):
        parts.append("")
        parts.append("■ Please note" if en else "■ 알아두실 점")
        parts.append(cfg["disclaimer"])
    return "\n".join(parts).strip()


def main():
    # 인자로 코드네임을 주면 그 앱만 다시 쓴다 (없으면 전체 — 다른 앱 md까지 덮어쓰니 주의)
    only = set(sys.argv[1:])
    for codename, cfg in APPS.items():
        if only and codename not in only:
            continue
        target = project_dir(codename) / "docs"
        if not target.parent.exists():
            print(f"건너뜀: {codename}")
            continue
        target.mkdir(parents=True, exist_ok=True)

        full = build_full(cfg)
        shots = "\n".join(
            f"{i}. **{t}** — {b.split('.')[0]}."
            for i, (t, b) in enumerate(cfg["features"][:5], start=1)
        )
        keywords = "\n".join(f"- {k}" for k in cfg["keywords"])

        cfg_en = APPS_EN[codename]
        full_en = build_full(cfg_en, en=True)
        en_block = TEMPLATE_EN.format(
            title=cfg_en["title"], title_len=len(cfg_en["title"]),
            short=cfg_en["short"], short_len=len(cfg_en["short"]),
            full=full_en, full_len=len(full_en),
            keywords="\n".join(f"- {k}" for k in cfg_en["keywords"]),
        )
        out = target / "store-listing.md"
        out.write_text(
            TEMPLATE.format(
                codename=codename,
                title=cfg["title"],
                title_len=len(cfg["title"]),
                short=cfg["short"],
                short_len=len(cfg["short"]),
                full=full,
                full_len=len(full),
                keywords=keywords,
                shots=shots,
            ) + en_block,
            encoding="utf-8",
        )
        warn = ""
        if len(cfg["title"]) > 30:
            warn += " [앱 이름 초과!]"
        if len(cfg["short"]) > 80:
            warn += " [간단한 설명 초과!]"
        w2 = ""
        if len(cfg_en["title"]) > 30: w2 += " [EN 이름 초과!]"
        if len(cfg_en["short"]) > 80: w2 += " [EN 짧은설명 초과!]"
        print(f"{codename:16} 한: {len(cfg['title'])}/{len(cfg['short'])}/{len(full)}{warn}"
              f"   영: {len(cfg_en['title'])}/{len(cfg_en['short'])}/{len(full_en)}{w2}")


if __name__ == "__main__":
    main()
